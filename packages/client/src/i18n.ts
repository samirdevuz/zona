const dicts: Record<Lang, Record<string, string>> = { uz, en };
let lang: Lang = 'uz';
const listeners: (() => void)[] = [];

export function setLang(l: Lang): void {
  lang = l;
  document.documentElement.lang = l;
  for (const fn of listeners) fn();
}
export function getLang(): Lang {
  return lang;
}
export function onLangChange(fn: () => void): void {
  listeners.push(fn);
}

/** Translate a key, replacing {name} placeholders. Falls back to English, then the key. */
export function t(key: string, params?: Record<string, string | number>): string {
  let s = dicts[lang][key] ?? en[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function hasKey(key: string): boolean {
  return key in uz && key in en;
}
export function allKeys(): { uz: string[]; en: string[] } {
  return { uz: Object.keys(uz), en: Object.keys(en) };
}
